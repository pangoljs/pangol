// Build step: scan src/routes, load each route definition, convert its schemas to
// plain TypeScript types and write .hyper/api.d.ts. The client never sees the
// server's code or schemas, only finished types.
//
// usage: tsx lib/build.ts <project dir>
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { z } from 'zod'

const project = path.resolve(process.argv[2] ?? '.')
const routesDir = path.join(project, 'src/routes')
const METHODS = ['get', 'post', 'put', 'patch', 'delete'] as const
type JS = Record<string, any>

function walk(dir: string): string[] {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name)
    return e.isDirectory() ? walk(p) : [p]
  })
}

// file "users/[id]/items/index.post.ts" -> ["POST", "/users/:id/items"]
function toRoute(file: string): [string, string] | null {
  const rel = path.relative(routesDir, file).split(path.sep)
  const m = rel[rel.length - 1].match(/^(.+)\.(get|post|put|patch|delete)\.ts$/)
  if (!m) return null
  const segs = [...rel.slice(0, -1), m[1]].filter((s) => s !== 'index')
  const p = '/' + segs.map((s) => (s.startsWith('[') ? ':' + s.slice(1, -1) : s)).join('/')
  return [m[2].toUpperCase(), p === '/' ? '/' : p.replace(/\/$/, '')]
}

const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k))

// JSON Schema -> TypeScript type text
function ts(s: JS): string {
  if (s.const !== undefined) return JSON.stringify(s.const)
  if (s.enum) return s.enum.map((v: unknown) => JSON.stringify(v)).join(' | ')
  const alt = s.anyOf ?? s.oneOf
  if (alt) return alt.map((x: JS) => ts(x)).join(' | ')
  if (s.allOf) return s.allOf.map((x: JS) => ts(x)).join(' & ')
  const t = Array.isArray(s.type) ? s.type : [s.type]
  if (t.length > 1) return t.map((x: string) => ts({ ...s, type: x })).join(' | ')
  switch (t[0]) {
    case 'string': return 'string'
    case 'number': case 'integer': return 'number'
    case 'boolean': return 'boolean'
    case 'null': return 'null'
    case 'array': return s.prefixItems ? `[${s.prefixItems.map(ts).join(', ')}]` : `Array<${s.items ? ts(s.items) : 'unknown'}>`
    case 'object': {
      const req = new Set<string>(s.required ?? [])
      const props = Object.entries<JS>(s.properties ?? {}).map(([k, v]) => `${key(k)}${req.has(k) ? '' : '?'}: ${ts(v)}`)
      if (s.additionalProperties && s.additionalProperties !== true) props.push(`[k: string]: ${ts(s.additionalProperties)}`)
      return `{ ${props.join('; ')} }`
    }
    default: return 'unknown'
  }
}

function jsonOf(schema: unknown, io: 'input' | 'output'): JS {
  const std = (schema as any)?.['~standard']
  if (std?.vendor !== 'zod') throw new Error('PoC converts Zod schemas only (vendor: ' + std?.vendor + ')')
  return z.toJSONSchema(schema as z.ZodType, { io, unrepresentable: 'any' }) as JS
}
const schemaType = (schema: unknown, io: 'input' | 'output') => ts(jsonOf(schema, io))

const started = performance.now()
const byMethod: Record<string, string[]> = { GET: [], POST: [], PUT: [], PATCH: [], DELETE: [] }
const problems: string[] = []
let count = 0
for (const file of walk(routesDir).sort()) {
  const r = toRoute(file)
  if (!r) continue
  const [method, p] = r
  const def = (await import(pathToFileURL(file).href)).default
  const where = path.relative(project, file)
  // security build checks (the full rule set lives in the framework; two shown here)
  if (!def?.auth) problems.push(`✖ ${where}\n  ${method} ${p} has no \`auth\`.\n  Fix: add auth: 'user', auth: { permission: '...' } or auth: 'public'`)
  if (!def?.response) problems.push(`✖ ${where}\n  ${method} ${p} has no \`response\` schema, so its output cannot be filtered or typed.\n  Fix: add response: <schema>`)
  if (!def) continue
  const input: string[] = []
  if (def.params) input.push(`params: ${schemaType(def.params, 'input')}`)
  if (def.query) {
    const q = jsonOf(def.query, 'input')
    input.push(`query${q.required?.length ? '' : '?'}: ${ts(q)}`) // optional when every field is optional
  }
  if (def.body) input.push(`body: ${schemaType(def.body, 'input')}`)
  const out = def.response ? schemaType(def.response, 'output') : 'unknown'
  byMethod[method].push(`    ${JSON.stringify(p)}: { input: ${input.length ? `{ ${input.join('; ')} }` : 'void'}; output: ${out} }`)
  count++
}
if (problems.length) {
  console.error(problems.join('\n\n'))
  process.exit(1)
}
const body = METHODS.map((m) => m.toUpperCase())
  .map((m) => `  ${m}: {\n${byMethod[m].join('\n')}\n  }`)
  .join('\n')
fs.mkdirSync(path.join(project, '.hyper'), { recursive: true })
fs.writeFileSync(path.join(project, '.hyper/api.d.ts'), `// generated by build — do not edit\nexport interface Api {\n${body}\n}\n`)
console.log(`codegen: ${count} routes in ${Math.round(performance.now() - started)} ms`)
