// `pangol build`: after a clean check, write .pangol/routes.ts, a static import table the app passes
// to createApp. Static imports keep the app free of file system access at run time and let any
// bundler see every route.
/// <reference types="node" />
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import type TS from 'typescript'
import type { CheckResult } from './check.js'

export const OUT_DIR = '.pangol'

/** '.ts' when the project imports TypeScript files by their own extension, otherwise '.js'. */
export function importExtension(ts: typeof TS, root: string): '.ts' | '.js' {
  const file = ts.findConfigFile(root, ts.sys.fileExists)
  if (file === undefined) return '.js'
  const { config } = ts.readConfigFile(file, ts.sys.readFile)
  const { options } = ts.parseJsonConfigFileContent(config ?? {}, ts.sys, dirname(file))
  return options.allowImportingTsExtensions === true || options.rewriteRelativeImportExtensions === true ? '.ts' : '.js'
}

export function routesModule(result: CheckResult, extension: '.ts' | '.js'): string {
  const lines = [
    '// Generated by `pangol build` from the files in src/routes. Do not edit: run `pangol build` again.',
    "import type { RouteKey } from 'pangol'",
  ]
  result.routes.forEach((r, i) => {
    const target = relative(OUT_DIR, r.file).split(sep).join('/').replace(/\.(m?)[jt]s$/, (_, m: string) => `.${m}${extension.slice(1)}`)
    lines.push(`import r${i} from ${JSON.stringify(target)}`)
  })
  lines.push('', 'export const routes = {')
  result.routes.forEach((r, i) => lines.push(`  ${JSON.stringify(r.key)}: r${i},`))
  lines.push('} as const satisfies Readonly<Record<RouteKey, object>>', '')
  return lines.join('\n')
}

export function writeRoutes(root: string, result: CheckResult, extension: '.ts' | '.js'): string {
  const file = join(root, OUT_DIR, 'routes.ts')
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, routesModule(result, extension))
  return file
}
